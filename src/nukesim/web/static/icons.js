/** An icon as inline SVG text, to put inside a button or a line of text. */
export function icon(name, cls = "") {
  const parts = ICONS[name];
  if (!parts) return "";
  const out = parts.map(([k, d, t]) => {
    const tr = t ? ` transform="translate(${t[1]} ${t[2]}) scale(${t[0]})"` : "";
    const sw = t ? ` stroke-width="${(1.8 / t[0]).toFixed(2)}"` : "";
    return k === "s" ? `<path d="${d}"${tr}${sw}/>` : `<path class="${k === "f" ? "icF" : "icB"}" d="${d}"${tr}/>`;
  }).join("");
  return `<svg class="ic${cls ? " " + cls : ""}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${out}</svg>`;
}

/** Draw an icon onto a 2D canvas, centred at (x, y), `size` pixels across, in one colour. */
export function drawIcon(g, name, x, y, size, color = "#fff") {
  const parts = ICONS[name];
  if (!parts || typeof Path2D === "undefined") return false;
  const s = size / 24;
  g.save();
  g.translate(x - size / 2, y - size / 2); g.scale(s, s);
  g.lineCap = "round"; g.lineJoin = "round";
  g.strokeStyle = color; g.fillStyle = color;
  for (const [k, d, t] of parts) {
    g.save();
    if (t) { g.translate(t[1], t[2]); g.scale(t[0], t[0]); }
    const p = new Path2D(d);
    if (k === "s") { g.lineWidth = 1.8 / (t ? t[0] : 1); g.stroke(p); }
    else { g.globalAlpha = k === "f" ? 0.25 : 1; g.fill(p); }
    g.restore();
  }
  g.restore();
  return true;
}

/** Fill in every <i data-icon="name"></i> placeholder inside `root` (for icons written in the HTML file). */
export function fillIcons(root = document) {
  root.querySelectorAll("i[data-icon]").forEach((el) => { el.outerHTML = icon(el.dataset.icon, el.className); });
}
